"""CKLB and XCCDF 1.1 export for Cisco IOS STIG assessments.

The CKLB shape is based on the repository's sanitized converter fixture. Import
into DISA STIG Viewer 3 is still required before claiming full interoperability.
"""
from __future__ import annotations

import copy
import json
import re
import uuid
from datetime import datetime, timezone
import xml.etree.ElementTree as ET
from pathlib import Path
from typing import Any, Iterable

from .stig_assessment import RuleRow

CKLB_NAMESPACE = uuid.UUID("f2bdc4f4-3e34-4bb9-8e89-20d09b1e3c1d")
XCCDF_NS = "http://checklists.nist.gov/xccdf/1.1"
ET.register_namespace("", XCCDF_NS)


def _stable_uuid(value: str) -> str:
    return str(uuid.uuid5(CKLB_NAMESPACE, value))


def _redact(value: Any) -> str:
    text = str(value if value is not None else "")
    text = re.sub(r"(?im)^\s*username\s+\S+.*?\b(?:secret|password)\s+\d+\s+\S+.*$", "username <REDACTED> secret <REDACTED>", text)
    text = re.sub(r"(?im)\b(?:enable\s+secret|password|secret)\s+\d+\s+\S+", "secret <REDACTED>", text)
    text = re.sub(r"(?im)\bsnmp-server\s+community\s+\S+", "snmp-server community <REDACTED>", text)
    text = re.sub(r"(?im)\bkey\s+7\s+\S+", "key 7 <REDACTED>", text)
    text = re.sub(r"(?is)-----BEGIN [^-]*PRIVATE KEY-----.*?-----END [^-]*PRIVATE KEY-----", "<REDACTED PRIVATE KEY>", text)
    return text


def _cell_status(row: RuleRow | None, level: str) -> tuple[str, str, str]:
    """Return (status, detail, depth) for the deepest evaluated cell."""
    if row is None:
        return "UNKNOWN", "No approved rule was executed for this catalog control.", "none"
    if level == "pro" and row.pro is not None and row.pro.status != "NOT_RUN":
        return row.pro.status, row.pro.detail, row.pro.depth
    if row.standard is not None:
        return row.standard.status, row.standard.detail, row.standard.depth
    if row.pro is not None and row.pro.status != "NOT_RUN":
        return row.pro.status, row.pro.detail, row.pro.depth
    return "UNKNOWN", "No applicable assessment cell was evaluated.", "none"


def _cklb_status(status: str) -> str:
    return {
        "PASS": "not_a_finding",
        "FAIL": "open",
        "UNKNOWN": "not_reviewed",
        "MANUAL": "not_reviewed",
        "NOT_APPLICABLE": "not_applicable",
        "WAIVED": "not_reviewed",
        "NOT_RUN": "not_reviewed",
    }.get(status, "not_reviewed")


def _cell_description(row: RuleRow | None, key: str) -> str:
    if row is None:
        return "not executed"
    cell = getattr(row, key)
    if cell is None:
        return "not applicable"
    suffix = " (presence only)" if cell.status == "PASS" and cell.depth == "presence" else ""
    return _redact(f"{cell.status} — {cell.detail}{suffix}")


def build_cklb(
    catalog: dict[str, Any],
    rows: Iterable[RuleRow],
    template_path: str | Path,
    stig_part: str,
    hostname: str,
    level: str = "pro",
) -> dict[str, Any]:
    """Build a checklist with every catalog control in the requested STIG part."""
    if level not in {"standard", "pro"}:
        raise ValueError("level must be standard or pro")
    template = json.loads(Path(template_path).read_text(encoding="utf-8"))
    if not isinstance(template, dict) or not isinstance(template.get("stigs"), list) or not template["stigs"]:
        raise ValueError("CKLB template must contain a non-empty stigs list")
    template_stig = template["stigs"][0]
    if not isinstance(template_stig, dict) or not isinstance(template_stig.get("rules"), list) or not template_stig["rules"]:
        raise ValueError("CKLB template STIG must contain a non-empty rules list")
    rule_template = template_stig["rules"][0]
    source = next((item for item in catalog.get("sources", []) if item.get("stig") == stig_part), None)
    if source is None:
        raise ValueError(f"unknown STIG part {stig_part!r}; expected one of L2S, NDM, RTR")
    controls = [item for item in catalog.get("controls", []) if item.get("stig") == stig_part]
    if not controls:
        raise ValueError(f"catalog contains no controls for STIG part {stig_part}")
    row_map = {item.control_id: item for item in rows}
    checklist = copy.deepcopy(template)
    checklist["title"] = f"NetAgent Cisco IOS Switch {stig_part} assessment - {hostname}"
    checklist["id"] = _stable_uuid(f"checklist:{stig_part}:{hostname}")
    checklist["active"] = True
    checklist["has_path"] = False
    target = checklist.get("target_data")
    if not isinstance(target, dict):
        target = {}
        checklist["target_data"] = target
    target.update({
        "target_type": "Network Device",
        "host_name": hostname,
        "ip_address": "",
        "mac_address": "",
        "fqdn": "",
        "comments": "Generated by netagent from local evidence; no live device access was performed by the exporter.",
        "role": "Network device",
    })
    stig_uuid = _stable_uuid(f"stig:{source['benchmark_id']}:{source.get('version')}:{source.get('release')}")
    output_rules = []
    for control in controls:
        row = row_map.get(control["control_id"])
        status, detail, _depth = _cell_status(row, level)
        item = copy.deepcopy(rule_template)
        control_id = str(control["control_id"])
        rule_id_src = str(control.get("rule_id") or control_id)
        item.update({
            "group_id_src": control_id,
            "group_tree": [{"id": control_id, "title": str(control.get("stig_id") or control_id), "description": "<GroupDescription></GroupDescription>"}],
            "group_id": control_id,
            "severity": str(control.get("severity", "medium")).lower(),
            "group_title": str(control.get("title") or control_id),
            "rule_id_src": rule_id_src,
            "rule_id": rule_id_src.removesuffix("_rule"),
            "rule_version": str(control.get("stig_id") or control_id),
            "rule_title": str(control.get("title") or control_id),
            "fix_text": str(control.get("fix_text") or ""),
            "weight": "10.0",
            "check_content": str(control.get("check_text") or ""),
            "check_content_ref": {"href": str(source.get("file") or ""), "name": "M"},
            "classification": "Unclassified",
            "discussion": str(control.get("description") or ""),
            "false_positives": "",
            "false_negatives": "",
            "documentable": "false",
            "security_override_guidance": "",
            "potential_impacts": "",
            "third_party_tools": "",
            "ia_controls": "",
            "responsibility": "",
            "mitigations": "",
            "mitigation_control": "",
            "legacy_ids": [],
            "ccis": list(control.get("cci") or []),
            "reference_identifier": control_id,
            "uuid": _stable_uuid(f"rule:{source['benchmark_id']}:{control_id}"),
            "stig_uuid": stig_uuid,
            "status": _cklb_status(status),
            "overrides": {},
            "comments": _redact(f"Standard: {_cell_description(row, 'standard')} / Pro: {_cell_description(row, 'pro')}"),
            # STIG Viewer finding_details is reserved for actual findings;
            # PASS, waiver, manual review, and unknown states belong in comments.
            "finding_details": _redact(detail) if status == "FAIL" else "",
            "srg_id": "",
        })
        output_rules.append(item)
    checklist["stigs"] = [{
        "stig_name": str(source.get("title") or f"Cisco IOS Switch {stig_part} STIG"),
        "display_name": f"Cisco IOS Switch {stig_part}",
        "stig_id": str(source.get("benchmark_id")),
        "release_info": f"Release: {source.get('release', '')} Benchmark Date: {source.get('date', '')}",
        "version": str(source.get("version", "")),
        "uuid": stig_uuid,
        "reference_identifier": str(source.get("benchmark_id")),
        "size": len(output_rules),
        "rules": output_rules,
    }]
    return checklist


def render_cklb(*args: Any, **kwargs: Any) -> str:
    return json.dumps(build_cklb(*args, **kwargs), ensure_ascii=False, indent=2) + "\n"


def build_xccdf_testresult(
    catalog: dict[str, Any],
    rows: Iterable[RuleRow],
    stig_part: str,
    hostname: str,
    level: str = "pro",
) -> ET.Element:
    """Build an XCCDF 1.1 TestResult for every control in the selected part."""
    if level not in {"standard", "pro"}:
        raise ValueError("level must be standard or pro")
    source = next((item for item in catalog.get("sources", []) if item.get("stig") == stig_part), None)
    if source is None:
        raise ValueError(f"unknown STIG part {stig_part!r}; expected one of L2S, NDM, RTR")
    row_map = {item.control_id: item for item in rows}
    controls = [item for item in catalog.get("controls", []) if item.get("stig") == stig_part]
    if not controls:
        raise ValueError(f"catalog contains no controls for STIG part {stig_part}")
    q = lambda name: f"{{{XCCDF_NS}}}{name}"
    result = ET.Element(q("TestResult"), {"id": f"netagent-{stig_part.lower()}-{_stable_uuid(hostname)[:8]}"})
    ET.SubElement(result, q("benchmark"), {"href": str(source.get("file") or ""), "id": str(source.get("benchmark_id"))})
    timestamp = datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")
    ET.SubElement(result, q("start-time")).text = timestamp
    ET.SubElement(result, q("end-time")).text = timestamp
    ET.SubElement(result, q("title")).text = f"NetAgent Cisco IOS Switch {stig_part} assessment"
    ET.SubElement(result, q("target")).text = hostname
    ET.SubElement(result, q("target-address")).text = "not collected"
    ET.SubElement(result, q("test-system")).text = "netagent read-only evidence assessment"
    for control in controls:
        row = row_map.get(str(control["control_id"]))
        status, detail, _depth = _cell_status(row, level)
        mapping = {
            "PASS": "pass",
            "FAIL": "fail",
            "NOT_APPLICABLE": "notapplicable",
            "WAIVED": "notchecked",
            "UNKNOWN": "notchecked",
            "MANUAL": "notchecked",
            "NOT_RUN": "notchecked",
        }
        rule_result = ET.SubElement(result, q("rule-result"), {"idref": str(control.get("rule_id") or control["control_id"])})
        ET.SubElement(rule_result, q("result")).text = mapping.get(status, "notchecked")
        message = f"{status}: {detail}"
        # Keep the selected Pro result while disclosing that Standard PASS
        # was based on presence-only evidence, so the report cannot imply a
        # stronger verification depth than was performed.
        if row is not None and row.standard is not None and row.standard.status == "PASS" and row.standard.depth == "presence":
            message += " (Standard PASS: presence only)"
        elif status == "PASS" and _depth == "presence":
            message += " (presence only)"
        ET.SubElement(rule_result, q("message"), {"severity": str(control.get("severity", "medium")).lower()}).text = _redact(message)
    return result


def render_xccdf_testresult(*args: Any, **kwargs: Any) -> str:
    root = build_xccdf_testresult(*args, **kwargs)
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding="unicode") + "\n"
